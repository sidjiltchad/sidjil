// تأكد تطابق المفاتيح بين اللغتين (يُستخدم في الاختبار)
export function missingKeys() {
  const a = new Set(Object.keys(STR.ar));
  const f = new Set(Object.keys(STR.fr));
  return {
    missingInFr: [...a].filter(k => !f.has(k)),
    missingInAr: [...f].filter(k => !a.has(k)),
  };
}

export function t(lang, key, vars = {}) {
  const l = SUPPORTED_LANGS.includes(lang) ? lang : 'ar';
  let s = STR[l][key];
  if (s === undefined) s = STR.ar[key];
  if (s === undefined) return key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll('{' + k + '}', String(v));
  }
  return s;
}

export function htmlDir(lang) {
  return lang === 'fr' ? 'ltr' : 'rtl';
}
